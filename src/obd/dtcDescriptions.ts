/**
 * Plain-English meanings for trouble codes.
 *
 * Generic codes (P0, P2, P3 and U0) mean the same on every vehicle (SAE J2012). Codes with
 * a 1 as the second character are the maker's own, so they are looked up per make, and a
 * code that isn't listed falls back to the system it belongs to.
 */

export interface CodeMeaning {
  readonly text: string;
  /** 'generic' for SAE codes, 'maker' for the manufacturer's own, 'group' when only the system is known. */
  readonly source: 'generic' | 'maker' | 'group';
}

