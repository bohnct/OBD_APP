/** Maker code books, by the start of the vehicle profile id they apply to. */
const CODE_BOOKS: readonly [string, Readonly<Record<string, string>>][] = [
  ['ford-f250-73', FORD_73],
];

/** Systems by the code's first three characters, for codes that aren't listed. */
const GROUPS: readonly [RegExp, string][] = [
  [/^P0[01]/, 'Fuel and air metering'],
  [/^P02/, 'Fuel and air metering (injector circuit)'],
  [/^P03/, 'Ignition system or misfire'],
  [/^P04/, 'Auxiliary emission controls'],
  [/^P05/, 'Vehicle speed, idle control and auxiliary inputs'],
  [/^P06/, 'Computer and output circuits'],
  [/^P0[789]/, 'Transmission'],
  [/^P1/, 'Powertrain, maker-specific code'],
  [/^P[23]/, 'Powertrain'],
  [/^C/, 'Chassis (brakes, steering, suspension)'],
  [/^B/, 'Body (airbags, lighting, comfort)'],
  [/^U/, 'Network communication between modules'],
];

/** What a code means on the vehicle with this profile id, as far as is known. */
export function describeCode(code: string, profileId: string): CodeMeaning {
  const book = CODE_BOOKS.find(([prefix]) => profileId.startsWith(prefix))?.[1];
  const maker = book?.[code];
  if (maker) return { text: maker, source: 'maker' };
  const generic = GENERIC[code];
  if (generic) return { text: generic, source: 'generic' };
  const group = GROUPS.find(([pattern]) => pattern.test(code));
  return { text: group ? group[1] : 'Unknown system', source: 'group' };
}
