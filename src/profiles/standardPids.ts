/** The catalogue as profile parameters (before validation). */
export const STANDARD_PARAMETERS = TABLE.map((s) => ({
  id: s.id,
  name: s.name,
  short: s.short,
  unit: s.unit,
  request: { type: 'obd', pid: s.pid.padStart(2, '0') },
  decode: {
    skip: s.skip ?? 0,
    bytes: s.bytes ?? 1,
    scale: s.scale ?? 1,
    offset: s.offset ?? 0,
    signed: s.signed ?? false,
    ...(s.bit === undefined ? {} : { bit: s.bit }),
  },
  range: [...s.range],
  ...(s.redline === undefined ? {} : { redline: s.redline }),
  ...(s.warnLow === undefined ? {} : { warnLow: s.warnLow }),
  ...(s.simulate === undefined ? {} : { simulate: { ...s.simulate } }),
  verified: true,
  source: 'standard',
}));
