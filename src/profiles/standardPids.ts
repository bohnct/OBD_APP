/**
 * The standard OBD-II mode 01 values (SAE J1979) that read as a single number.
 *
 * Every vehicle gets these on top of its own profile. Which ones it actually has is asked
 * at connect (the "supported PIDs" bitmaps), so a vehicle only shows what it reports.
 * Values that are bit fields or need more than a linear formula are left out.
 *
 * Decoding is value = raw × scale + offset over the first `bytes` data bytes (big-endian).
 */

interface Std {
  readonly pid: string;
  readonly id: string;
  readonly name: string;
  readonly short: string;
  readonly unit: string;
  readonly skip?: number;
  readonly bytes?: number;
  readonly scale?: number;
  readonly offset?: number;
  readonly signed?: boolean;
  readonly bit?: number;
  readonly range: readonly [number, number];
  readonly redline?: number;
  readonly warnLow?: number;
  /** Simulator only: typical values at idle and under load. */
  readonly simulate?: { readonly idle: number; readonly load: number };
}

